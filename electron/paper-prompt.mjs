function cleanInline(value) {
  return String(value || "").replace(/[\r\n]+/g, " ").trim();
}

export function buildPaperTurnPrompt({
  mode,
  characterCount,
  papers,
  currentPaperTitle,
  currentPage,
  hasSelection,
  question,
  coverage,
  hasPageImage = false,
  answerDepth = "deep",
  pageImages = [],
}) {
  const multiple = mode === "all";
  const paperList = papers.map((paper, index) => (
    `${index + 1}. ${cleanInline(paper.title)}${paper.pageCount ? `（${paper.pageCount} 页）` : ""}${/^[a-f0-9]{24}$/.test(paper.id ?? "") ? `；证据引用：[第 N 页](#paper=${paper.id}&page=N)，N 必须替换为实际 PDF 页码` : ""}`
  )).join("\n");
  const attention = currentPaperTitle && currentPage
    ? `《${cleanInline(currentPaperTitle)}》第 ${currentPage} 页`
    : "无";

  return [
    "<任务上下文>",
    `对话模式：${multiple ? `全部 ${papers.length} 篇论文综合比较` : "单篇论文全文解读"}`,
    `本轮资料：已提供 ${Number(characterCount || 0).toLocaleString("zh-CN")} 个分页提取字符${coverage ? `，覆盖 ${coverage.providedPages}/${coverage.totalPages} 页，${coverage.complete ? "全部已提取文字" : "仅相关页面或节选；不可推断未提供页面的结论"}` : ""}。文字覆盖不代表图像覆盖；无文字层的扫描页和图表只能依据本轮附图，不能把未附图页面说成已读。`,
    `论文清单：\n${paperList}`,
    `当前注意力定位：${attention}`,
    `选中摘录：${hasSelection ? "已作为不可信资料单独提供" : "无"}`,
    `原文页图：${pageImages.length ? pageImages.map((image) => `论文 ${image.paperId}，PDF 第 ${image.page} 页`).join("；") : hasPageImage ? "已提供当前页" : "未提供；不得声称已看清页面图像"}。只能把附图作为对应页的视觉证据。`,
    "</任务上下文>",
    "",
    "<回答协议>",
    "先直接回答用户真正提出的问题。",
    answerDepth === "brief" ? "本轮默认回答深度：简短。优先用 1–3 段回答核心问题，保留必要证据与限定，不铺开无关章节。用户在问题中明确指定深度时，以用户问题为准。"
      : answerDepth === "balanced" ? "本轮默认回答深度：标准。先给结论，再解释关键机制与证据；只展开理解问题所需的细节。用户在问题中明确指定深度时，以用户问题为准。"
      : "本轮默认回答深度：充实、深入、完整。除非用户明确要求简短，否则应覆盖完成问题所需的机制、因果关系、实现细节、实验证据和限制条件；不要用一句结论或几个标签代替分析。",
    ...(answerDepth === "deep" ? [
    "如果用户在问概览、总结、解读或‘这篇做了什么’，请按下面主干组织：",
    "1. 一句话总览：解决什么问题，核心答案是什么。",
    "2. 方法：详细说明问题定义、输入/输出、关键假设、主要算法，以及训练和推理流程；解释每个关键设计解决了什么困难。",
    "3. 网络/系统架构：详细拆解关键组件、组件关系、信息流或数据流、张量/状态如何变化，以及关键模块在训练与推理时的作用；不适用时明确说明。",
    "4. 核心创新：逐项使用‘原有瓶颈 → 本文改变 → 为什么有效 → 全文证据’的链条说明，并区分作者声称的新意与实验真正支持的新意。",
    "5. 实验依据：任务/数据集、基线、指标、主要结果、消融、效率或鲁棒性；说明每组实验支持了什么、尚未证明什么。",
    "6. 局限与边界：分别列出作者写明的局限与基于全文证据的分析推断，并说明适用条件和外推风险。",
    "7. 阅读导航：给出最值得回看的 2–4 个页码及原因。",
    "概览类回答不得只写一句话总览：资料充分时必须继续完成方法、架构、创新、实验和局限；其中方法与架构应占主要篇幅。问题很具体时可以只保留相关部分，但仍要完整解释机制、证据与限定，不为了套模板而添加无关内容。多篇比较时按方法、架构、创新、实验证据、局限对齐后，再总结主要差异与取舍。",
    ] : ["概览围绕研究问题、方法、证据和局限；具体问题只解释相关部分，不强制套用完整解读提纲。"]),
    "每个关键事实、实验数字和结构判断都尽可能紧邻页码引用。无法从当前资料可靠确认时，明确写出‘当前资料无法可靠确认’。",
    "</回答协议>",
    "",
    "<用户问题>",
    String(question || "").trim(),
    "</用户问题>",
  ].join("\n");
}
